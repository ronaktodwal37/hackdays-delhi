// Helper to interact with Gemini API directly
async function translateTextWithGemini(
  text: string,
  targetLang: string,
  apiKey: string
): Promise<string> {
  const url = `https://generativelanguage.googleapis.com/v1beta/models/gemini-1.5-flash:generateContent?key=${apiKey}`;
  const response = await fetch(url, {
    method: "POST",
    headers: {
      "Content-Type": "application/json"
    },
    body: JSON.stringify({
      contents: [
        {
          parts: [
            {
              text: `Translate the following English business requirement document text into formal, professional ${targetLang}. Preserve the formatting and bullet points exactly. Do not output any translator notes or intro. Just output the translation itself:\n\n${text}`
            }
          ]
        }
      ]
    })
  });

  if (!response.ok) {
    throw new Error(`Gemini translation API failed with status ${response.status}`);
  }

  const data = await response.json();
  const content = data.candidates?.[0]?.content?.parts?.[0]?.text;
  if (!content) {
    throw new Error("Invalid response format from Gemini API");
  }

  return content.trim();
}
